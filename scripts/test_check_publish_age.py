"""Tests for check_publish_age.py. Run: python3 -I -m unittest discover -s scripts"""

import datetime as dt
import pathlib
import sys
import tempfile
import unittest

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import check_publish_age as cpa  # noqa: E402

NOW = dt.datetime(2026, 11, 10, 12, 0, tzinfo=dt.timezone.utc)

LOCK = """# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "flying-microwave"
version = "0.1.0"
dependencies = [
 "old-crate",
]

[[package]]
name = "old-crate"
version = "1.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "00"

[[package]]
name = "new-crate"
version = "2.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "00"

[[package]]
name = "git-crate"
version = "0.1.0"
source = "git+https://example.invalid/repo#abc"
"""

INDEX = {
    "old-crate": [{"vers": "1.0.0", "pubtime": "2026-10-01T00:00:00Z"}],
    "new-crate": [
        {"vers": "1.9.0", "pubtime": "2026-01-01T00:00:00Z"},
        {"vers": "2.0.0", "pubtime": "2026-11-08T00:00:00Z"},
    ],
    "ancient-crate": [{"vers": "0.1.0"}],
}


def fake_fetch(name):
    return INDEX.get(name)


class IndexPathTest(unittest.TestCase):
    def test_paths_follow_the_sparse_index_layout(self):
        self.assertEqual(cpa.index_path("a"), "1/a")
        self.assertEqual(cpa.index_path("ab"), "2/ab")
        self.assertEqual(cpa.index_path("abc"), "3/a/abc")
        self.assertEqual(cpa.index_path("Winit"), "wi/ni/winit")


class LockParseTest(unittest.TestCase):
    def test_only_registry_packages_are_listed(self):
        self.assertEqual(
            cpa.registry_packages(LOCK),
            [("old-crate", "1.0.0"), ("new-crate", "2.0.0")],
        )

    def test_packages_from_other_sources_are_reported(self):
        # Local path packages have no source and are not dependencies to check.
        self.assertEqual(
            cpa.other_sources(LOCK),
            [("git-crate", "0.1.0", "git+https://example.invalid/repo#abc")],
        )


class CheckTest(unittest.TestCase):
    def check(self, packages):
        return cpa.check(packages, NOW, dt.timedelta(days=7), fake_fetch)

    def test_an_old_version_passes(self):
        self.assertEqual(self.check([("old-crate", "1.0.0")]), [])

    def test_a_version_newer_than_the_cooldown_fails(self):
        problems = self.check([("new-crate", "2.0.0")])
        self.assertEqual(len(problems), 1)
        self.assertIn("new-crate 2.0.0", problems[0])

    def test_the_boundary_is_exactly_the_cooldown(self):
        limit = NOW - dt.timedelta(days=7)
        index = {"edge": [{"vers": "1.0.0", "pubtime": limit.strftime("%Y-%m-%dT%H:%M:%SZ")}]}
        problems = cpa.check([("edge", "1.0.0")], NOW, dt.timedelta(days=7), index.get)
        self.assertEqual(problems, [])

    def test_a_version_without_pubtime_fails(self):
        # Every crates.io version checked so far has a pubtime, so a missing
        # one is unexpected and must not pass (fail closed).
        problems = self.check([("ancient-crate", "0.1.0")])
        self.assertEqual(len(problems), 1)
        self.assertIn("ancient-crate 0.1.0", problems[0])

    def test_an_unknown_version_fails(self):
        problems = self.check([("old-crate", "9.9.9")])
        self.assertEqual(len(problems), 1)
        self.assertIn("old-crate 9.9.9", problems[0])

    def test_an_unknown_crate_fails(self):
        self.assertEqual(len(self.check([("missing-crate", "1.0.0")])), 1)


class MainTest(unittest.TestCase):
    def run_main(self, args):
        return cpa.main(args, now=NOW, fetch=fake_fetch)

    def test_main_fails_on_a_lock_with_a_new_version(self):
        with tempfile.TemporaryDirectory() as d:
            lock = pathlib.Path(d, "Cargo.lock")
            lock.write_text(LOCK)
            self.assertEqual(self.run_main([str(lock)]), 1)

    def test_main_checks_an_extra_crate(self):
        self.assertEqual(self.run_main(["--crate", "old-crate@1.0.0"]), 0)
        self.assertEqual(self.run_main(["--crate", "new-crate@2.0.0"]), 1)

    def test_main_fails_on_a_dependency_from_another_source(self):
        with tempfile.TemporaryDirectory() as d:
            lock = pathlib.Path(d, "Cargo.lock")
            lock.write_text(LOCK.replace('name = "new-crate"', 'name = "new-crate-x"'))
            index = dict(INDEX, **{"new-crate-x": [{"vers": "2.0.0", "pubtime": "2026-01-01T00:00:00Z"}]})
            self.assertEqual(cpa.main([str(lock)], now=NOW, fetch=index.get), 1)

    def test_main_rejects_a_malformed_crate_argument(self):
        self.assertEqual(self.run_main(["--crate", "no-version"]), 2)


if __name__ == "__main__":
    unittest.main()
